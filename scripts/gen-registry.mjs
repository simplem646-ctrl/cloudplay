#!/usr/bin/env node
// Generates src/_generated/registry.js: static imports for every content/map module, so
// workers add FILES in their own directories and never edit a shared index (no merge
// conflicts). Run automatically by `npm run build` and `npm test`. The output is gitignored.
//
// Directory conventions (every *.js except index.js is picked up):
//   src/world/maps/*.js          default export = MapDef  (key = file name)
//   src/content/events/*.js      default export = EventDef[]   (or named export `events`)
//   src/content/dialogue/*.js    default export = DialoguePool (one npc) or DialoguePool[]
//   src/content/schedules/*.js   default export = Schedule (one npc) or Schedule[]
//   src/content/exams/*.js       default export = { subject, questions:[...] }
//   src/content/quests/*.js      default export = { quest_id: { title, summary, main?, steps? }, ... }
//   src/content/endings/*.js     default export = { slides: [ ...Slide ] }

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src', '_generated');
const groups = [
  ['MAP_MODULES', 'src/world/maps'],
  ['EVENT_MODULES', 'src/content/events'],
  ['DIALOGUE_MODULES', 'src/content/dialogue'],
  ['SCHEDULE_MODULES', 'src/content/schedules'],
  ['EXAM_MODULES', 'src/content/exams'],
  ['QUEST_MODULES', 'src/content/quests'],
  ['ENDING_MODULES', 'src/content/endings'],
];

let out = '// AUTO-GENERATED by scripts/gen-registry.mjs. Do not edit. Do not commit.\n';
let n = 0;
const bodies = [];
for (const [name, dir] of groups) {
  const abs = path.join(root, dir);
  const files = fs.existsSync(abs)
    ? fs.readdirSync(abs).filter((f) => f.endsWith('.js') && f !== 'index.js').sort()
    : [];
  const entries = [];
  for (const f of files) {
    const id = `m${n++}`;
    const rel = path.posix.relative('src/_generated', `${dir}/${f}`);
    out += `import * as ${id} from '${rel.startsWith('.') ? rel : './' + rel}';\n`;
    entries.push(`  ${JSON.stringify(f.replace(/\.js$/, ''))}: ${id},`);
  }
  bodies.push(`export const ${name} = {\n${entries.join('\n')}\n};\n`);
}
out += '\n' + bodies.join('\n');

// Optional registrar modules (a SEPARATE generated file, src/_generated/registrars.js, so that content/sim modules that import the
// registry never sit in an import cycle with the scene/sim entry points). Each task adds ONE entry-point file that registers its
// scenes/directors/hooks; it is listed only when the file exists, so boot code can call them all without a hard dependency
// (a missing task = a missing feature, never a failed build). Call order is the order below.
const registrars = [
  ['src/sim/academics_index.js', 'registerAcademics', 'academics'],
  ['src/scenes/activities/index.js', 'registerActivityScenes', 'activities'],
  ['src/scenes/academics/index.js', 'registerAcademicScenes', 'academic scenes'],
  ['src/scenes/menus/index.js', 'registerMenuScenes', 'menus'],
];
let regOut = '// AUTO-GENERATED by scripts/gen-registry.mjs. Do not edit. Do not commit.\n// Registrar entry points that exist in this tree: call each `fn` once at boot (see src/scenes/boot.js).\n';
const regEntries = [];
registrars.forEach(([file, fn, label], i) => {
  if (!fs.existsSync(path.join(root, file))) return;
  const rel = path.posix.relative('src/_generated', file);
  regOut += `import * as r${i} from '${rel.startsWith('.') ? rel : './' + rel}';\n`;
  regEntries.push(`  { label: ${JSON.stringify(label)}, name: ${JSON.stringify(fn)}, fn: r${i}[${JSON.stringify(fn)}] },`);
});
regOut += `\nexport const REGISTRARS = [\n${regEntries.join('\n')}\n].filter((r) => typeof r.fn === 'function');\n`;

fs.mkdirSync(outDir, { recursive: true });
for (const [name, text] of [['registry.js', out], ['registrars.js', regOut]]) {
  const target = path.join(outDir, name);
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) fs.writeFileSync(target, text);
}
console.log(`[gen-registry] ${n} module(s) registered`);
